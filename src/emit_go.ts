import { InternalError } from "./errors";
import {
  IRArithOp, IRComparand, IRCompareOp, IRCondition, IRData, IRExpr, IRFunction, IRRoot, IRSource, IRStatement,
  IRResult, IRSubstring, IRTarget, IRType, IRVariable,
} from "./ir";

/** Emits package main for one root. The runtime is imported from the runtime module as `abap2go/abap`. */
export function emitGo(root: IRRoot): string {
  temporaryCount = 0;
  labelCount = 0;
  targets.clear();
  const out: string[] = [];
  out.push(`// Code generated by abap2go from ${root.name}. DO NOT EDIT.`);
  out.push("");
  out.push("package main");
  out.push("");
  out.push(`import "abap2go/abap"`);
  out.push("");
  out.push("func main() {");
  out.push("\tabap.Run(func(session *abap.Session) {");
  out.push("\t\t_ = session");
  switch (root.kind) {
    case "report":
      out.push(`\t\tlist := abap.NewList(${root.lineSize ?? 0})`);
      out.push(...indent(processing(root.blocks), 2));
      out.push("\t\tlist.End()");
      break;
    case "classrun":
      out.push("\t\tout := abap.NewConsole()");
      out.push("\t\t_ = out");
      out.push(...indent(processing([root.body]), 2));
      break;
  }
  out.push("\t})");
  out.push("}");
  out.push("");
  return out.join("\n");
}

function indent(lines: string[], depth = 1): string[] {
  return lines.map(l => "\t".repeat(depth) + l);
}

/** The processing block being emitted, which CHECK outside a loop leaves. */
let current = { label: "", last: true, used: false };

/**
 * The processing blocks of the root, run one after the other by a function literal, so that return ends all of them
 * and what follows the call (the end of the list) still runs. Returning from within loops does not set sy-index back
 * to its value before them; nothing can observe that, as nothing of the program runs afterwards.
 */
function processing(blocks: IRStatement[][]): string[] {
  // DATA is not executable: every variable exists from the start, with its start value
  const data = blocks.flatMap(declarations).flatMap(statement);
  const run = blocks.flatMap((body, k) => {
    // CHECK leaves the last block by returning, an earlier one by breaking out of a loop that runs it once
    current = { label: `block${k + 1}`, last: k === blocks.length - 1, used: false };
    const lines = block(body);
    return [
      ...(k === 0 ? [] : ["list.NewBlock()"]), // only a report has several blocks
      ...(current.used ? [`${current.label}:`, "for {", ...indent([...lines, "break"]), "}"] : lines),
    ];
  });
  return [...data, "func() {", ...indent(run), "}()"];
}

/** The Go statement by which CHECK leaves the processing block being emitted. */
function leaveBlock(): string {
  const block = current;
  if (block.last) {
    return leave("r", 0, () => "return");
  }
  return leave(`k${block.label.slice("block".length)}`, 0, () => {
    block.used = true;
    return `break ${block.label}`;
  });
}

/** The DATA statements of a block and of the blocks nested in it, in order. */
function declarations(body: IRStatement[]): IRData[] {
  return body.flatMap((s): IRData[] => {
    switch (s.kind) {
      case "data": return [s];
      case "if": return [...s.branches.flatMap(b => declarations(b.body)), ...declarations(s.otherwise ?? [])];
      case "case":
        return [...declarations(s.first), ...s.branches.flatMap(b => declarations(b.body)), ...declarations(s.otherwise ?? [])];
      case "do": case "while": return declarations(s.body);
      case "try": return [...declarations(s.body), ...s.catches.flatMap(c => declarations(c.body)), ...declarations(s.cleanup ?? [])];
      default: return [];
    }
  });
}

/** The statements of a block without its declarations, which emitGo puts first. */
function block(body: IRStatement[]): string[] {
  return body.flatMap(s => s.kind === "data" ? [] : statement(s));
}

/**
 * The Go temporaries of the subfields, functions and CASE results of the statement being emitted: type and value,
 * computed by abap.Substring, abap.ValueOf or abap.CaseValue before they are used, since the type can depend on what
 * is known only at run time (the offsets of a subfield, the decimals of abs( ) of a text or of a p result).
 */
const temporaries = new Map<IRSubstring | IRFunction | IRResult, string>();
let temporaryCount = 0;

/** Adds the lines that compute source's subfield, function or result, if it is one, to lines. */
function hoist(lines: string[], source: IRComparand | undefined): void {
  if (source?.kind === "function" && !temporaries.has(source)) {
    hoistExpr(lines, source.call); // the subfield its argument may be
    const name = `fn${++temporaryCount}`;
    temporaries.set(source, name);
    lines.push(`${name}T, ${name} := abap.MustValueOf(${expr(source.call)})`, `_, _ = ${name}T, ${name}`);
  } else if (source?.kind === "result" && !temporaries.has(source)) {
    hoistExpr(lines, source.expression);
    const name = `res${++temporaryCount}`;
    temporaries.set(source, name);
    lines.push(`${name}T, ${name} := abap.MustCaseValue(${expr(source.expression)})`, `_, _ = ${name}T, ${name}`);
  } else if (source?.kind === "substring" && !temporaries.has(source)) {
    const name = `sub${++temporaryCount}`;
    temporaries.set(source, name);
    const [off, len] = bounds(source);
    lines.push(`${name}T, ${name} := ${substring(source, off, len)}`, `_, _ = ${name}T, ${name}`);
  }
}

/** The offset and length of a subfield as Go expressions, 0 for the one not given. */
function bounds(source: IRSubstring): [string, string] {
  const bound = (b: IRSubstring["offset"]) => b === undefined ? "0" : convert(b, { kind: "i" });
  return [bound(source.offset), bound(source.length)];
}

/** The abap.Substring call that gives the type and the value of a subfield at offset off with length len. */
function substring(source: IRSubstring, off: string, len: string): string {
  return `abap.Substring(${goTypeValue(source.base.type)}, ${goName(source.base)}, ${off}, ${len}, ${source.length !== undefined})`;
}

function hoistExpr(lines: string[], e: IRExpr): void {
  switch (e.kind) {
    case "operand": hoist(lines, e.source); return;
    case "strlen": hoist(lines, e.arg); return;
    case "binary": hoistExpr(lines, e.left); hoistExpr(lines, e.right); return;
    case "unary": hoistExpr(lines, e.operand); return;
    case "ipow": hoistExpr(lines, e.base); hoistExpr(lines, e.exp); return;
  }
}

/** The lines of one statement: its subfields first, then the statement. Conditions compute their own subfields. */
function statement(s: IRStatement): string[] {
  const lines: string[] = [];
  switch (s.kind) {
    case "list_write": case "data": hoist(lines, s.value); break;
    case "console_write": hoist(lines, s.value); hoist(lines, s.name); break;
    case "move": hoist(lines, s.target); hoist(lines, s.source); break;
    case "calculate": hoist(lines, s.target); hoistExpr(lines, s.expression); break;
    case "case": hoist(lines, s.operand); break;
    case "do":
      if (s.times?.kind === "into_i") {
        hoistExpr(lines, s.times.expression);
      } else {
        hoist(lines, s.times);
      }
      break;
  }
  return [...lines, ...statementOnly(s)];
}

/** Assigns value, a Go expression of the target's type, to target. */
function assign(target: IRTarget, value: string): string {
  if (target.kind === "variable") {
    return `${goName(target)} = ${value}`;
  }
  const off = target.offset === undefined ? "0" : convert(target.offset, { kind: "i" });
  return `${goName(target.base)} = abap.Overwrite(${goTypeValue(target.base.type)}, ${goName(target.base)}, ${off}, ${value})`;
}

/**
 * The enclosing loops, innermost last: EXIT, CONTINUE and CHECK in a loop refer to the innermost one by its label.
 * depth is the number of function literals (the blocks of a TRY) around the loop.
 */
const loops: { label: string; used: boolean; depth: number }[] = [];
let labelCount = 0;

/**
 * The blocks of the TRYs being emitted are function literals, innermost last. A jump out of a literal returns its
 * name: "break loop3" as "b3", "continue loop3" as "c3", leaving the processing block as "r", breaking out of
 * processing block 2 as "k2". escapes collects the names per TRY, so the code after the TRY can jump on or return the
 * name further out; targets holds, per name, the depth of the literal the jump goes to and its Go statement there.
 */
const escapes: Set<string>[] = [];
const targets = new Map<string, { depth: number; go: () => string }>();

/** The Go statement of a jump to depth: go( ) there, or returning name from the TRY literals in between. */
function leave(name: string, depth: number, go: () => string): string {
  if (depth < escapes.length) {
    targets.set(name, { depth, go });
    escapes[escapes.length - 1].add(name);
    return `return "${name}"`;
  }
  return go();
}

/** The statement that breaks out of the innermost loop or goes on with its next pass. */
function jump(kind: "break" | "continue"): string {
  const loop = loops[loops.length - 1];
  if (loop === undefined) {
    throw new InternalError("EXIT, CONTINUE or CHECK outside a loop");
  }
  return leave(`${kind[0]}${loop.label.slice("loop".length)}`, loop.depth, () => {
    loop.used = true;
    return `${kind} ${loop.label}`;
  });
}

/** A function literal returning the jump that left it, "" at its end (see escapes). */
function closure(head: string, body: string[]): string[] {
  return [`${head} {`, ...indent(body), "\treturn \"\"", "}"];
}

/** A call whose arguments span lines: each argument starts on the line where the one before it ends. */
function call(fn: string, args: string[][]): string[] {
  const lines = [`${fn}(`];
  args.forEach((arg, i) => {
    lines[lines.length - 1] += (i === 0 ? "" : ", ") + arg[0];
    lines.push(...arg.slice(1));
  });
  lines[lines.length - 1] += ")";
  return lines;
}

/**
 * TRY as abap.Session.Try (runtime/go/abap/try.go). Its blocks are function literals, so the jumps that leave them
 * come back as names (see escapes): after the TRY, a jump whose target is in the same literal is made there, any
 * other name is returned to the literal around it.
 */
function tryStatement(s: IRStatement & { kind: "try" }): string[] {
  const names = new Set<string>();
  escapes.push(names);
  const body = closure("func() string", block(s.body));
  const handler = s.catches.length === 0 ? ["nil"] : closure("func(k int) string", [
    "switch k {",
    ...s.catches.flatMap((c, k) => [`case ${k}:`, ...indent(block(c.body))]),
    "}",
  ]);
  const cleanup = s.cleanup === undefined ? ["nil"] : ["func() {", ...indent(block(s.cleanup)), "}"];
  escapes.pop();
  const catches = s.catches.length === 0 ? "nil"
    : `[][]string{${s.catches.map(c => `{${c.classes.map(n => JSON.stringify(n)).join(", ")}}`).join(", ")}}`;
  const lines = call("session.Try", [body, [catches], handler, cleanup]);
  if (names.size === 0) {
    return lines;
  }
  const cases: string[] = [];
  let returns = false;
  for (const name of [...names].sort()) {
    const target = targets.get(name)!;
    if (target.depth === escapes.length) {
      cases.push(`case "${name}":`, `\t${target.go()}`);
    } else {
      escapes[escapes.length - 1].add(name);
      returns = true;
    }
  }
  if (returns) {
    cases.push("default:", "\treturn j");
  }
  lines[0] = `if j := ${lines[0]}`;
  lines[lines.length - 1] += `; j != "" {`;
  return [...lines, "\tswitch j {", ...indent(cases), "\t}", "}"];
}

/**
 * A loop that sets sy-index to the number of each pass and back to its value before the loop when it ends. head is
 * the for clause, before the lines ahead of the loop, start the lines at the start of each pass after sy-index is
 * set.
 */
function loop(head: string, before: string[], start: string[], body: IRStatement[]): string[] {
  const entry = { label: `loop${++labelCount}`, used: false, depth: escapes.length };
  loops.push(entry);
  const inner = [...start, ...block(body)];
  loops.pop();
  return [
    "{",
    ...indent([
      "saved := session.Sy.Index",
      ...before,
      ...(entry.used ? [`${entry.label}:`] : []),
      `for ${head} {`,
      ...indent(["session.Sy.Index = pass", ...inner]),
      "}",
      "session.Sy.Index = saved",
    ]),
    "}",
  ];
}

function statementOnly(s: IRStatement): string[] {
  switch (s.kind) {
    case "list_write":
      return [`list.Write(${listText(s.value)}, ${s.newLine})`];
    case "console_write":
      return [`out.Write(${toString(s.value)}, ${s.name === undefined ? `""` : toString(s.name)})`];
    case "data": {
      const init = s.value === undefined
        ? `abap.Initial(${goTypeValue(s.variable.type)}).(${goType(s.variable.type)})`
        : convert(s.value, s.variable.type);
      return [`${goName(s.variable)} := ${init}`, `_ = ${goName(s.variable)}`];
    }
    case "move":
      if (s.target.kind === "variable" && s.source.kind !== "substring" && sameType(s.source.type, s.target.type)) {
        return [assign(s.target, operand(s.source))];
      }
      return [store(s.target, "Move", `${typeValue(s.source)}, ${operand(s.source)}`)];
    case "calculate":
      return [store(s.target, "Compute", expr(s.expression))];
    case "assert":
      return [`abap.Assert(${condition(s.condition)})`];
    case "if":
      return branches(s.branches.map(b => ({ condition: () => condition(b.condition), body: b.body })), s.otherwise);
    case "case":
      return caseStatement(s);
    case "do": {
      if (s.times === undefined) {
        return loop("pass := int32(1); ; pass++", [], [], s.body);
      }
      const times = s.times.kind === "into_i"
        ? `abap.MustCalculate[int32](${expr(s.times.expression)}, abap.TypeI)`
        : convert(s.times, { kind: "i" });
      return loop("pass := int32(1); pass <= times; pass++", [`times := ${times}`], [], s.body);
    }
    case "while":
      return loop("pass := int32(1); ; pass++", [], [`if !${condition(s.condition)} {`, "\tbreak", "}"], s.body);
    case "exit":
      return [jump("break")];
    case "continue":
      return [jump("continue")];
    case "check":
      return [`if !${condition(s.condition)} {`, `	${s.leaves === "pass" ? jump("continue") : leaveBlock()}`, "}"];
    case "return":
      return [leave("r", 0, () => "return")];
    case "try":
      return tryStatement(s);
    case "retry":
      // RETRY is only allowed directly in a CATCH block (loops aside), so it returns from the CATCH literal
      return ["return abap.Retry"];
  }
}

/**
 * The statements before the first WHEN, then the branches. The operand has been computed (see hoist), which for a
 * subfield of a flat variable is a copy: it is taken again after those statements, at the same offset and length.
 */
function caseStatement(s: IRStatement & { kind: "case" }): string[] {
  const before: string[] = [];
  const after: string[] = [];
  const operand = s.operand;
  if (s.first.length > 0 && operand.kind === "substring" && operand.base.type.kind !== "string"
      && operand.base.type.kind !== "xstring") {
    const name = temporary(operand);
    const saved = bounds(operand).map(b => `int32(${b})`); // a bound not given is the constant 0
    before.push(`${name}Off, ${name}Len := ${saved.join(", ")}`);
    after.push(`${name}T, ${name} = ${substring(operand, `${name}Off`, `${name}Len`)}`);
  }
  return [...before, ...block(s.first), ...after, ...branches(s.branches.map(b => ({
    condition: () => b.values.map(v => condition({ kind: "compare", op: "=", left: operand, right: v })).join(" || "),
    body: b.body,
  })), s.otherwise)];
}

/**
 * An if chain over the branches of IF or CASE, with the lines of otherwise as its else; without a branch (a CASE with
 * no WHEN but WHEN OTHERS, if any) just those lines.
 */
function branches(list: { condition: () => string; body: IRStatement[] }[], otherwise: IRStatement[] | undefined): string[] {
  if (list.length === 0) {
    return block(otherwise ?? []);
  }
  const lines: string[] = [];
  list.forEach((b, k) => {
    lines.push(`${k === 0 ? "if" : "} else if"} ${b.condition()} {`, ...indent(block(b.body)));
  });
  if (otherwise !== undefined) {
    lines.push("} else {", ...indent(block(otherwise)));
  }
  lines.push("}");
  return lines;
}

/**
 * target = what fn (abap.Move or abap.Compute) computes from args, of the target's type: the value an exception
 * leaves in the target is stored before it is raised.
 */
function store(target: IRTarget, fn: "Move" | "Compute", args: string): string {
  if (target.kind === "variable") {
    return `abap.${fn}(&${goName(target)}, ${args}, ${goTypeValue(target.type)})`;
  }
  const set = `func(r string) { ${assign(target, "r")} }`;
  return `abap.${fn}To(${set}, ${args}, ${typeValue(target)})`;
}

const GO_COMPARE: Record<IRCompareOp, string> = { "=": "==", "<>": "!=", "<": "<", ">": ">", "<=": "<=", ">=": ">=" };

/**
 * A Go bool expression of a condition, in parentheses unless it is a call. && and || stop as ABAP's AND and OR do;
 * == evaluates both sides, as EQUIV does. Each relational expression computes its subfields when it is evaluated.
 */
function condition(c: IRCondition): string {
  switch (c.kind) {
    case "compare":
      return relational([c.left, c.right], [], () =>
        `(abap.MustCompare(${typeValue(c.left)}, ${operand(c.left)}, ${typeValue(c.right)}, ${operand(c.right)}) ${GO_COMPARE[c.op]} 0)`);
    case "compare_calc":
      return relational([], [c.left, c.right], () => `(abap.MustCompareCalculated(${expr(c.left)}, ${expr(c.right)}) ${GO_COMPARE[c.op]} 0)`);
    case "between_calc":
      // the subfields of high are computed before the comparison with low; exact as long as computing them raises
      // nothing
      return relational([], [c.operand, c.low, c.high], () => `abap.MustBetweenCalculated(${expr(c.operand)}, ${expr(c.low)}, ${expr(c.high)})`);
    case "not":
      return `!${condition(c.operand)}`;
    case "and":
      return `(${condition(c.left)} && ${condition(c.right)})`;
    case "or":
      return `(${condition(c.left)} || ${condition(c.right)})`;
    case "equiv":
      return `(${condition(c.left)} == ${condition(c.right)})`;
  }
}

/** A relational expression; with subfields or functions, a function literal that computes them first, from the left. */
function relational(sources: IRComparand[], exprs: IRExpr[], build: () => string): string {
  const lines: string[] = [];
  sources.forEach(s => hoist(lines, s));
  exprs.forEach(e => hoistExpr(lines, e));
  const go = build();
  return lines.length === 0 ? go : `func() bool { ${lines.join("; ")}; return ${go} }()`;
}

const GO_OPS: Record<IRArithOp, string> = {
  "+": "OpAdd", "-": "OpSubtract", "*": "OpMultiply", "/": "OpDivide", "DIV": "OpDiv", "MOD": "OpMod", "**": "OpPower",
};

/** The abap.Expr tree of an arithmetic expression. */
function expr(e: IRExpr): string {
  switch (e.kind) {
    case "operand":
      return `abap.Operand(${typeValue(e.source)}, ${operand(e.source)})`;
    case "strlen":
      return `abap.Strlen(${typeValue(e.arg)}, ${operand(e.arg)})`;
    case "binary":
      return `abap.Binary(abap.${GO_OPS[e.op]}, ${expr(e.left)}, ${expr(e.right)})`;
    case "unary":
      return `abap.${{ "-": "Negate", "abs": "Abs", "sqrt": "Sqrt" }[e.fn]}(${expr(e.operand)})`;
    case "ipow":
      return `abap.Ipow(${expr(e.base)}, ${expr(e.exp)})`;
  }
}

/**
 * The source converted to type to, by the runtime's conversion rules, as an operand; a plain copy when the types are
 * the same. Assignments go through store, which keeps the value an exception leaves.
 */
function convert(source: IRSource, to: IRType): string {
  if (source.kind !== "substring" && sameType(source.type, to)) {
    return operand(source);
  }
  return `abap.MustConvert[${goType(to)}](${typeValue(source)}, ${operand(source)}, ${goTypeValue(to)})`;
}

/** The abap.Type of a source or target: that of a subfield, function or result comes from its temporary. */
function typeValue(source: IRComparand): string {
  return source.kind === "substring" || source.kind === "function" || source.kind === "result"
    ? `${temporary(source)}T` : goTypeValue(source.type);
}

function temporary(source: IRSubstring | IRFunction | IRResult): string {
  const name = temporaries.get(source);
  if (name === undefined) {
    throw new InternalError("subfield or function not computed before its use");
  }
  return name;
}

/** The text WRITE outputs: a text literal as it is, anything else formatted with the user settings. */
function listText(source: IRSource): string {
  if (source.kind === "literal" && (source.type.kind === "c" || source.type.kind === "string")) {
    return goText(source.value);
  }
  return `abap.Format(session.Settings, ${typeValue(source)}, ${operand(source)})`;
}

function toString(source: IRSource): string {
  return convert(source, { kind: "string" });
}

function sameType(a: IRType, b: IRType): boolean {
  return JSON.stringify(a) === JSON.stringify(b);
}

function operand(source: IRComparand): string {
  if (source.kind === "variable") {
    return goName(source);
  }
  if (source.kind === "substring" || source.kind === "function" || source.kind === "result") {
    return temporary(source);
  }
  if (source.kind === "system_field") {
    return "session.Sy.Index";
  }
  switch (source.type.kind) {
    case "i":
      return `int32(${source.value})`;
    case "p":
      return `abap.MustConvert[abap.Packed](abap.TypeString, ${goText(source.value)}, ${goTypeValue(source.type)})`;
  }
  return goText(source.value);
}

/** Variables get a prefix, so no ABAP name collides with a Go keyword or the generated names. */
function goName(v: IRVariable): string {
  return "v_" + v.name.replace(/[^a-z0-9_]/g, "_");
}

function goType(t: IRType): string {
  switch (t.kind) {
    case "c": case "n": case "d": case "t": case "string": case "x": case "xstring":
      return "string";
    case "i": return "int32";
    case "int8": return "int64";
    case "b": return "uint8";
    case "s": return "int16";
    case "p": return "abap.Packed";
    case "f": return "float64";
    case "decfloat16": case "decfloat34": return "abap.Decfloat";
    case "utclong": return "abap.Utclong";
  }
}

/** The abap.Type value of t. */
function goTypeValue(t: IRType): string {
  switch (t.kind) {
    case "c": return `abap.TypeC(${t.length})`;
    case "n": return `abap.TypeN(${t.length})`;
    case "x": return `abap.TypeX(${t.length})`;
    case "p": return `abap.TypeP(${t.length}, ${t.decimals})`;
    case "d": return "abap.TypeD";
    case "t": return "abap.TypeT";
    case "string": return "abap.TypeString";
    case "xstring": return "abap.TypeXString";
    case "i": return "abap.TypeI";
    case "int8": return "abap.TypeInt8";
    case "b": return "abap.TypeB";
    case "s": return "abap.TypeS";
    case "f": return "abap.TypeF";
    case "decfloat16": return "abap.TypeDecfloat16";
    case "decfloat34": return "abap.TypeDecfloat34";
    case "utclong": return "abap.TypeUtclong";
  }
}

/**
 * A Go string literal of ABAP text: the UTF-16 code units of text, big-endian, as the runtime holds text. JavaScript
 * strings are UTF-16 already, so each char code is one code unit.
 */
function goText(text: string): string {
  let out = "";
  const hex = (b: number) => "\\x" + b.toString(16).padStart(2, "0");
  for (let i = 0; i < text.length; i++) {
    const u = text.charCodeAt(i);
    if (u >= 0x20 && u < 0x7f && u !== 0x22 && u !== 0x5c) {
      out += "\\x00" + String.fromCharCode(u);
    } else {
      out += hex(u >> 8) + hex(u & 0xff);
    }
  }
  return `"${out}"`;
}
